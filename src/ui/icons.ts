export type IconName = keyof typeof ICONS;

/** The icon as SVG markup: one rect per run of same-coloured pixels in a row. */
export function icon(name: IconName): string {
  const rects: string[] = [];
  ICONS[name].forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      const c = row[x]!;
      let end = x + 1;
      while (row[end] === c) end++;
      if (c !== '.') rects.push(`<rect x="${x}" y="${y}" width="${end - x}" height="1" fill="${PAINT[c]}"/>`);
      x = end;
    }
  });
  return `<svg class="icon" viewBox="0 0 12 12" aria-hidden="true" focusable="false" shape-rendering="crispEdges">${rects.join('')}</svg>`;
}

/** Fills every `<span data-icon="name">` under `root` with its icon. */
export function fillIcons(root: ParentNode = document): void {
  for (const el of root.querySelectorAll<HTMLElement>('[data-icon]')) el.innerHTML = icon(el.dataset.icon as IconName);
}
